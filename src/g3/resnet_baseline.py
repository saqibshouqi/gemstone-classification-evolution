# --- Data Preparation ---
class GemstoneDataset(Dataset):
    def __init__(self, csv_file, image_dir, split_type, class_names, transform=None):
        self.data = pd.read_csv(csv_file)
        self.data = self.data[self.data['split'] == split_type].reset_index(drop=True)
        self.image_dir = image_dir
        self.transform = transform
        self.classes = class_names
        self.class_to_idx = {cls_name: i for i, cls_name in enumerate(self.classes)}

        valid_indices = []
        self.resolved_paths = []
        print(f"Scanning and verifying {split_type} files on disk...")
        for idx in range(len(self.data)):
            rel_path = self.data.loc[idx, 'path']
            if rel_path.startswith('Gem Stone Images Dataset/'):
                rel_path = rel_path.replace('Gem Stone Images Dataset/', '', 1)

            actual_path = get_case_insensitive_path(self.image_dir, rel_path)
            if actual_path and os.path.exists(actual_path):
                valid_indices.append(idx)
                self.resolved_paths.append(actual_path)

        print(f"Found {len(valid_indices)} out of {len(self.data)} physical images for {split_type}.")
        if len(valid_indices) != len(self.data):
            print(f"WARNING: Missing {len(self.data) - len(valid_indices)} images in {split_type}!")
        self.data = self.data.iloc[valid_indices].reset_index(drop=True)

    def __len__(self):
        return len(self.data)

    def __getitem__(self, idx):
        img_path = self.resolved_paths[idx]
        image = Image.open(img_path).convert('RGB')
        label = self.class_to_idx[self.data.loc[idx, 'class']]

        if self.transform:
            image = self.transform(image)

        return image, label, self.data.loc[idx, 'path']

# Transformations as specified in the 2022 paper
train_transforms = transforms.Compose([
    transforms.RandomResizedCrop(224),
    transforms.RandomHorizontalFlip(),
    transforms.RandomVerticalFlip(),
    transforms.ToTensor(),
    transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])
])

test_transforms = transforms.Compose([
    transforms.Resize(256),
    transforms.CenterCrop(224),
    transforms.ToTensor(),
    transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])
])

train_dataset = GemstoneDataset(CSV_PATH, IMG_DIR, 'train', CLASS_NAMES, transform=train_transforms)
test_dataset = GemstoneDataset(CSV_PATH, IMG_DIR, 'test', CLASS_NAMES, transform=test_transforms)

# Weighted Random Sampling
full_counts = np.zeros(NUM_CLASSES)
for i, cls_name in enumerate(CLASS_NAMES):
    count = len(train_dataset.data[train_dataset.data['class'] == cls_name])
    full_counts[i] = count if count > 0 else 1

class_weights = 1. / full_counts
sample_weights = [class_weights[train_dataset.class_to_idx[cls]] for cls in train_dataset.data['class']]

device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print(f"Using device: {device}")

# --- Run Across Seeds ---
for SEED in SEEDS:
    print(f"\n========== Running {MODEL_NAME} | Seed {SEED} ==========")
    random.seed(SEED)
    np.random.seed(SEED)
    torch.manual_seed(SEED)
    torch.cuda.manual_seed_all(SEED)

    generator = torch.Generator().manual_seed(SEED)
    sampler = WeightedRandomSampler(
        weights=sample_weights, num_samples=len(sample_weights), replacement=True, generator=generator
    )

    train_loader = DataLoader(train_dataset, batch_size=BATCH_SIZE, sampler=sampler, num_workers=2, pin_memory=True)
    test_loader = DataLoader(test_dataset, batch_size=1, shuffle=False, num_workers=2, pin_memory=True)

    # Model Setup
    if MODEL_NAME == 'resnet50':
        model = models.resnet50(weights=models.ResNet50_Weights.IMAGENET1K_V1)
    else:
        model = models.resnet18(weights=models.ResNet18_Weights.IMAGENET1K_V1)

    for param in model.parameters():
        param.requires_grad = False

    model.fc = nn.Linear(model.fc.in_features, NUM_CLASSES)
    model = model.to(device)

    optimizer = optim.SGD(model.fc.parameters(), lr=0.001, momentum=0.9)
    scheduler = optim.lr_scheduler.StepLR(optimizer, step_size=7, gamma=0.1)
    criterion = nn.CrossEntropyLoss()

    # Training Loop
    for epoch in range(EPOCHS):
        model.train()
        running_loss = 0.0
        for inputs, labels, _ in train_loader:
            inputs, labels = inputs.to(device), labels.to(device)
            optimizer.zero_grad()
            outputs = model(inputs)
            loss = criterion(outputs, labels)
            loss.backward()
            optimizer.step()
            running_loss += loss.item() * inputs.size(0)

        scheduler.step()
        print(f"Epoch {epoch+1:02d}/{EPOCHS} - Loss: {running_loss/len(train_dataset):.4f}")

    # Save checkpoint to Drive
    pt_path = os.path.join(OUT_DIR, f'{MODEL_NAME}_s{SEED}.pt')
    torch.save(model.state_dict(), pt_path)

    # Evaluation & CSV Generation
    model.eval()
    predictions_list = []

    with torch.no_grad():
        for inputs, labels, paths in test_loader:
            inputs, labels = inputs.to(device), labels.to(device)
            outputs = model(inputs)
            probabilities = torch.nn.functional.softmax(outputs, dim=1).cpu().numpy()[0]

            row_data = {
                'path': paths[0],
                'true': CLASS_NAMES[labels.item()],
                'where': 'test'
            }
            for i, cls_name in enumerate(CLASS_NAMES):
                row_data[cls_name] = probabilities[i]

            predictions_list.append(row_data)

    df_preds = pd.DataFrame(predictions_list)
    csv_path_out = os.path.join(OUT_DIR, f'{ARM_PREFIX}_{MODEL_NAME}_rgb_s{SEED}.csv')
    df_preds.to_csv(csv_path_out, index=False)

    # Quick Accuracy Verification
    probs = df_preds[CLASS_NAMES].values
    true_idx = df_preds['true'].map(train_dataset.class_to_idx).values
    top1 = (probs.argmax(axis=1) == true_idx).mean() * 100
    top5 = np.mean([t in np.argsort(p)[-5:] for t, p in zip(true_idx, probs)]) * 100
    print(f"Saved: {csv_path_out}")
    print(f"--> {MODEL_NAME} (seed {SEED}) | Top-1: {top1:.2f}% | Top-5: {top5:.2f}%")