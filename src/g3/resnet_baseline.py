# --- Case-Insensitive Path Helper ---
def get_case_insensitive_path(base_path, relative_path):
    parts = relative_path.replace('\\', '/').strip('/').split('/')
    current_path = base_path
    for part in parts:
        if not os.path.exists(current_path):
            return None
        try:
            items = os.listdir(current_path)
        except OSError:
            return None
        matched = [item for item in items if item.lower() == part.lower()]
        if matched:
            current_path = os.path.join(current_path, matched[0])
        else:
            return None
    return current_path

# --- Load Fixed Class Order (Contract 1 & 3) ---
