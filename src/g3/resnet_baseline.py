# --- Configuration ---
MODEL_NAME = 'resnet18'   # Change to 'resnet18' for the second model
ARM_PREFIX = 'g3'         # Confirm with Package A if they prefer 'g2' or 'g3' for ResNet baselines
NUM_CLASSES = 68
BATCH_SIZE = 16
EPOCHS = 25
SEEDS = [4]               # Test with [0] first, then run [1, 2, 3, 4]

